def _ask_ollama(question, system):
    body = {
        "model": OLLAMA_MODEL,
        "stream": False,
        "options": {"temperature": 0.3, "num_predict": 500},
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": question},
        ],
    }
    req = urllib.request.Request(
        OLLAMA_URL + "/api/chat",
        data=json.dumps(body).encode(),
        headers={"content-type": "application/json"},
    )
    data = json.loads(urllib.request.urlopen(req, timeout=120).read())
    return (data.get("message", {}).get("content") or "").strip()


def _ask_claude(question, system):
    body = {
        "model": MODEL,
        "max_tokens": 700,
        "system": system,
        "messages": [{"role": "user", "content": question}],
    }
    req = urllib.request.Request(
        API_URL,
        data=json.dumps(body).encode(),
        headers={
            "content-type": "application/json",
            "x-api-key": os.environ["ANTHROPIC_API_KEY"],
            "anthropic-version": "2023-06-01",
        },
    )
    data = json.loads(urllib.request.urlopen(req, timeout=25).read())
    return "".join(b.get("text", "") for b in data.get("content", []) if b.get("type") == "text").strip()


def _ask_gemini(question, system):
    for model in GEMINI_MODELS:
        body = {
            "system_instruction": {"parts": [{"text": system}]},
            "contents": [{"role": "user", "parts": [{"text": question}]}],
            "generationConfig": {"temperature": 0.3, "maxOutputTokens": 2000},
        }
        if "2.5" in model and "flash" in model:
            # без «размышлений» ответ приходит быстрее и не обрезается лимитом токенов
            body["generationConfig"]["thinkingConfig"] = {"thinkingBudget": 0}
        req = urllib.request.Request(
            GEMINI_URL.format(model=model),
            data=json.dumps(body).encode(),
            headers={"content-type": "application/json", "x-goog-api-key": _gemini_key()},
        )
        try:
            data = json.loads(urllib.request.urlopen(req, timeout=25).read())
            parts = data.get("candidates", [{}])[0].get("content", {}).get("parts", [])
            text = "".join(p.get("text", "") for p in parts).strip()
            if text:
                return text
        except urllib.error.HTTPError as e:
            print(f"Gemini {model}: HTTP {e.code}", e.read()[:200])
        except Exception as e:
            print(f"Gemini {model}:", e)
    return ""


def ask_ai(question, crew_context="", kb_text=""):
    """Ответ ИИ или None, если ИИ недоступен или все запросы не удались."""
    system = _system_prompt(crew_context, kb_text)
    for provider in providers():
        try:
            if provider == "gemini":
                text = _ask_gemini(question, system)
            elif provider == "claude":
                text = _ask_claude(question, system)
            else:
                text = _ask_ollama(question, system)
            if text:
                return text
        except urllib.error.HTTPError as e:
            print(f"AI error ({provider}): HTTP {e.code}", e.read()[:200])
        except Exception as e:
            print(f"AI error ({provider}):", e)
    return None
