def find_condition(q):
    """Вернёт ключ болезни по тексту вопроса или None."""
    for key, c in CONDITIONS.items():
        if any(re.search(p, q) for p in c["patterns"]):
            return key
    return None


def condition_text(key):
    c = CONDITIONS[key]
    steps = "\n".join(f"{i}. {s}" for i, s in enumerate(c["steps"], 1))
    return f"{c['title']}. Что делать:\n{steps}\nКогда срочно к врачу: {c['red']}\n{DISCLAIMER}"


def conditions_list():
    return [{"id": k, "title": c["title"]} for k, c in CONDITIONS.items()]


