_ollama_cache = {"t": 0.0, "ok": False}


def ollama_available():
    """Проверка, запущена ли Ollama и есть ли модель. Результат кэшируется на 20 секунд."""
    now = time.time()
    if now - _ollama_cache["t"] < 20:
        return _ollama_cache["ok"]
    ok = False
    try:
        data = json.loads(urllib.request.urlopen(OLLAMA_URL + "/api/tags", timeout=1).read())
        names = [m.get("name", "") for m in data.get("models", [])]
        base = OLLAMA_MODEL.split(":")[0]
        ok = any(n == OLLAMA_MODEL or n.split(":")[0] == base for n in names)
    except Exception:
        ok = False
    _ollama_cache.update(t=now, ok=ok)
    return ok


def providers():
    """Все доступные ИИ по приоритету: gemini, claude, ollama."""
    out = []
    if _gemini_key():
        out.append("gemini")
    if os.environ.get("ANTHROPIC_API_KEY"):
        out.append("claude")
    if ollama_available():
        out.append("ollama")
    return out


def ai_provider():
    """Главный ИИ: 'gemini', 'claude', 'ollama' или None."""
    if _gemini_key():
        return "gemini"
    if os.environ.get("ANTHROPIC_API_KEY"):
        return "claude"
    return "ollama" if ollama_available() else None


def ai_enabled():
    return ai_provider() is not None


